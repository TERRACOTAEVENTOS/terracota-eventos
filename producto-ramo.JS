const whatsappAgs = "5214493639750";
const whatsappLeon = "521477 849 4417";

document.addEventListener("DOMContentLoaded", () => {
  const parametros = new URLSearchParams(window.location.search);
  const claveRamo = parametros.get("ramo");
  const ramo = ramos[claveRamo];

  // Estos IDs coinciden con producto-ramo.html
  const nombre = document.getElementById("nombreRamo");
  const descripcion = document.getElementById("descripcionRamo");
  const imagenPrincipal = document.getElementById("fotoPrincipal");
  const galeria = document.getElementById("miniaturasRamo");
  const botonAgs = document.getElementById("whatsappAgs");
  const botonLeon = document.getElementById("whatsappLeon");

  if (!ramo) {
    if (nombre) nombre.textContent = "Ramo no encontrado";
    if (descripcion) {
      descripcion.textContent =
        "No encontramos este diseño. Regresa al catálogo y selecciona un ramo.";
    }
    return;
  }

  document.title = `${ramo.nombre} | Terracota Eventos`;

  if (nombre) nombre.textContent = ramo.nombre;
  if (descripcion) descripcion.textContent = ramo.descripcion;

  // Regresar a la página del catálogo correspondiente
  const enlaceVolver = document.querySelector(".volver-catalogo");
  const ramosPaginaDos = ["eva", "lucia", "aurora", "cala"];

  if (enlaceVolver) {
    enlaceVolver.href = ramosPaginaDos.includes(claveRamo)
      ? "ramosdenovia2.html"
      : "ramosdenovia.html";
  }

  // Galería de imágenes
  if (imagenPrincipal && galeria) {
    galeria.replaceChildren();

    ramo.imagenes.forEach((ruta, indice) => {
      const miniatura = document.createElement("button");
      miniatura.type = "button";
      miniatura.className = "miniatura-ramo";
      miniatura.setAttribute(
        "aria-label",
        `Ver imagen ${indice + 1} de ${ramo.nombre}`
      );

      const imagen = document.createElement("img");
      imagen.src = ruta;
      imagen.alt = `${ramo.nombre}, imagen ${indice + 1}`;

      // Oculta las miniaturas si el archivo no existe
      imagen.addEventListener("error", () => {
        miniatura.remove();

        if (indice === 0) {
          imagenPrincipal.removeAttribute("src");
          imagenPrincipal.alt = "";
        }
      });

      miniatura.appendChild(imagen);

      miniatura.addEventListener("click", () => {
        imagenPrincipal.src = ruta;
        imagenPrincipal.alt = ramo.nombre;

        galeria.querySelectorAll(".miniatura-ramo").forEach((boton) => {
          boton.classList.remove("activa");
        });

        miniatura.classList.add("activa");
      });

      galeria.appendChild(miniatura);

      if (indice === 0) {
        imagenPrincipal.src = ruta;
        imagenPrincipal.alt = ramo.nombre;
        miniatura.classList.add("activa");
      }
    });
  }

  // Mensaje de WhatsApp con el nombre del ramo
  const mensaje = encodeURIComponent(
    `Hola, me interesa información sobre el ramo de novia ${ramo.nombre} de Terracota Eventos.`
  );

  if (botonAgs) {
    botonAgs.href = `https://wa.me/${whatsappAgs}?text=${mensaje}`;
    botonAgs.target = "_blank";
    botonAgs.rel = "noopener noreferrer";
  }

  if (botonLeon) {
    botonLeon.href = `https://wa.me/${whatsappLeon}?text=${mensaje}`;
    botonLeon.target = "_blank";
    botonLeon.rel = "noopener noreferrer";
  }
});
